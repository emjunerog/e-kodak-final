// Flattened list of every major and extension campus across Cebu for direct 1-click predictive search
export const ALL_CEBU_CAMPUSES = CEBU_UNIVERSITIES.flatMap(univ => {
  if (univ.id === "other") {
    return [{
      id: "other_custom",
      univId: "other",
      univName: "Other College / University",
      shortName: "Other",
      campusName: "Custom Campus",
      schoolDisplay: "Other College / University (Custom)",
      fullAddress: "Custom Campus / Address",
      campusLocation: "Cebu",
      isExtension: false
    }];
  }

  return (univ.campuses || []).map((campusStr, idx) => {
    const commaIndex = campusStr.indexOf(",");
    const campusTitle = commaIndex !== -1 ? campusStr.substring(0, commaIndex).trim() : campusStr.trim();
    const campusLoc = commaIndex !== -1 ? campusStr.substring(commaIndex + 1).trim() : campusStr;
    const isExtension = campusTitle.toLowerCase().includes("extension");

    return {
      id: `${univ.id}_${idx}`,
      univId: univ.id,
      univName: univ.name,
      shortName: univ.shortName,
      campusName: campusTitle,
      // Full descriptive school string to populate the form
      schoolDisplay: univ.campuses.length > 1
        ? `${univ.name} - ${campusTitle}`
        : univ.name,
      fullAddress: campusStr,
      campusLocation: campusLoc,
      isExtension
    };
  });
});

